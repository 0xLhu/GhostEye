"""JSON / HTML export of a triage report."""

import html
import json

SEV_COLOR = {"high": "#d1242f", "medium": "#bc4c00", "low": "#9a6700", "info": "#57606a"}


def to_json(report):
    return json.dumps(report, indent=2, default=str, ensure_ascii=False)


def to_html(report):
    e = lambda v: html.escape(str(v if v is not None else ""))
    s = report["system"]
    rows = []
    for f in report["findings"]:
        ev = "<br>".join(f"<b>{e(k)}</b>: {e(', '.join(v) if isinstance(v, list) else v)}" for k, v in f["evidence"].items())
        rows.append(
            f"<tr><td><span class='sev' style='background:{SEV_COLOR[f['severity']]}'>{e(f['severity'])}</span></td>"
            f"<td>{e(f['category'])}</td><td>{e(f['process'])}{' (' + e(f['pid']) + ')' if f['pid'] else ''}</td>"
            f"<td><b>{e(f['title'])}</b><div class='d'>{e(f['detail'])}</div><div class='ev'>{ev}</div></td>"
            f"<td>{'<br>'.join(e(m['id']) for m in f['mitre'])}</td></tr>")
    counts = " · ".join(f"<b style='color:{SEV_COLOR[k]}'>{v}</b> {k}" for k, v in report["counts"].items())
    tech = "".join(f"<li><b>{e(t)}</b> {e(n)}</li>" for t, n in report["techniques"])
    skipped = "".join(f"<li>{e(x['name'])} ({e(x['pid'])}): {e(x['reason'])}</li>" for x in report["skipped"])
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>GhostEye: {e(s['hostname'])}</title>
<style>body{{font:14px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;max-width:1100px;margin:32px auto;padding:0 20px;color:#1f2328}}
h1{{margin:0}}h2{{border-bottom:2px solid #8957e5;padding-bottom:4px;margin-top:28px}}
table{{border-collapse:collapse;width:100%;font-size:13px}}td,th{{border:1px solid #d0d7de;padding:6px 8px;vertical-align:top;text-align:left}}
th{{background:#f6f8fa}}.sev{{color:#fff;border-radius:10px;padding:1px 8px;font-size:11px;text-transform:uppercase}}
.d{{color:#57606a}}.ev{{font:12px ui-monospace,monospace;color:#57606a;margin-top:4px;word-break:break-all}}.meta td{{border:0;padding:2px 12px 2px 0}}</style></head><body>
<h1>GhostEye triage report</h1>
<table class="meta"><tr><td>Host</td><td><b>{e(s['hostname'])}</b> ({e(s['os'])})</td></tr>
<tr><td>Date</td><td>{e(report['started'])} ({e(report['duration_s'])} s)</td></tr>
<tr><td>Mode</td><td>{e(s['mode'])} · admin: {e(s['admin'])} · SeDebugPrivilege: {e(s['debug_privilege'])}</td></tr>
<tr><td>Findings</td><td>{counts}</td></tr></table>
<h2>Findings</h2><table><tr><th>Severity</th><th>Category</th><th>Process</th><th>Finding</th><th>ATT&amp;CK</th></tr>{''.join(rows)}</table>
<h2>ATT&amp;CK techniques</h2><ul>{tech or '<li>None</li>'}</ul>
<h2>Not inspected</h2><ul>{skipped or '<li>None</li>'}</ul>
<p style="color:#57606a">Generated by GhostEye (live memory inspection, read-only).</p></body></html>"""
